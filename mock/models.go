// /api/copy, /api/delete, /api/blobs.

func (s *Server) details(m *installed) map[string]any {
	d := map[string]any{
		"parent_model": m.Parent, "format": m.Format, "family": m.Arch, "families": []string{m.Arch},
		"parameter_size": m.ParameterSize(), "quantization_level": m.Quant,
	}
	if m.Runner != "" {
		d["runner"] = m.Runner
	}
	return d
}

func (s *Server) handleTags(w http.ResponseWriter, r *http.Request) {
	list := []map[string]any{}
	for _, m := range s.sortedModels() {
		list = append(list, map[string]any{
			"name": m.Name, "model": m.Name, "modified_at": m.Modified.Format(time.RFC3339Nano),
			"size": m.Size, "digest": m.Digest, "details": s.details(m),
		})
	}
	writeJSON(w, 200, map[string]any{"models": list})
}

func (s *Server) handlePS(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	s.expire()
	type entry struct {
		m *installed
		r runner
	}
	var entries []entry
	for name, rn := range s.loaded {
		if m := s.models[name]; m != nil {
			entries = append(entries, entry{m, *rn})
		}
	}
	s.mu.Unlock()
	slices.SortFunc(entries, func(a, b entry) int { return strings.Compare(a.m.Name, b.m.Name) })
	list := []map[string]any{}
	for _, e := range entries {
		expires := e.r.expires
		if expires.IsZero() {
			expires = time.Now().Add(time.Duration(math.MaxInt64))
		}
		list = append(list, map[string]any{
			"name": e.m.Name, "model": e.m.Name, "size": e.r.size, "digest": e.m.Digest,
			"details": s.details(e.m), "expires_at": expires.Format(time.RFC3339Nano),
			"size_vram": e.r.size, "context_length": e.r.numCtx,
		})
	}
	writeJSON(w, 200, map[string]any{"models": list})
}

func (s *Server) handleShow(w http.ResponseWriter, r *http.Request) {
	var body struct {
		Model string `json:"model"`
		Name  string `json:"name"`
	}
	if err := decode(r, &body); err != nil {
		writeError(w, 400, err.Error())
		return
	}
	name := body.Model
	if name == "" {
		name = body.Name
	}
	noteModel(r, name)
	m, err := s.lookup(name)
	if err != nil {
		writeError(w, 404, fmt.Sprintf("model '%s' not found", name))
		return
	}
	template, stops := templateFor(m)
	params := []string{}
	for _, st := range stops {
		params = append(params, fmt.Sprintf("stop %q", st))
	}
	if m.Has("thinking") {
		params = append(params, "temperature 0.6", "top_k 20", "top_p 0.95")
	}
	for k, v := range m.Parameters {
		params = append(params, fmt.Sprintf("%s %v", k, v))
	}
	slices.Sort(params)
	license := licenseFor(m.Model)
	modelfile := fmt.Sprintf("# Modelfile generated by \"ollama show\"\n# To build a new Modelfile based on this, replace FROM with:\n# FROM %s\n\nFROM /usr/share/ollama/.ollama/models/blobs/sha256-%s\nTEMPLATE \"\"\"%s\"\"\"\n",
		m.Name, m.Digest, template)
	if m.System != "" {
		modelfile += fmt.Sprintf("SYSTEM \"\"\"%s\"\"\"\n", m.System)
	}
	for _, p := range params {
		modelfile += "PARAMETER " + p + "\n"
	}
	modelfile += fmt.Sprintf("LICENSE \"\"\"%s\"\"\"\n", license)
	res := map[string]any{
		"license": license, "modelfile": modelfile, "parameters": strings.Join(params, "\n"),
		"template": template, "details": s.details(m), "model_info": modelInfo(m.Model),
		"capabilities": m.Capabilities, "modified_at": m.Modified.Format(time.RFC3339Nano),
	}
	if m.System != "" {
		res["system"] = m.System
	}
	writeJSON(w, 200, res)
}

func modelInfo(m Model) map[string]any {
	a := m.Arch
	emb := max(m.EmbeddingLength, 64)
	heads := max(emb/128, 1)
	info := map[string]any{
		"general.architecture":         a,
		"general.basename":             basename(m),
		"general.file_type":            fileType(m.Quant),
		"general.parameter_count":      int64(m.Params * 1e9),
		"general.quantization_version": 2,
		a + ".context_length":          m.ContextLength,
		a + ".embedding_length":        emb,
		a + ".block_count":             m.BlockCount(),
		a + ".attention.head_count":    heads,
		a + ".attention.head_count_kv": max(heads/4, 1),
		a + ".feed_forward_length":     roundTo(float64(emb)*2.7, 256),
		"tokenizer.ggml.model":         "gpt2",
	}
	if m.Has("embedding") {
		info[a+".pooling_type"] = 1
		info["tokenizer.ggml.model"] = "bert"
	}
	if m.Active < m.Params*0.9 {
		info[a+".expert_count"] = 128
		info[a+".expert_used_count"] = 8
	}
	return info
}

func basename(m Model) string {
	base, _ := splitTag(m.Name)
	base = base[strings.LastIndex(base, "/")+1:]
	parts := strings.FieldsFunc(base, func(r rune) bool { return r == '-' || r == '_' })
	for i, p := range parts {
		parts[i] = upperFirst(p)
	}
	return strings.Join(parts, "-")
}

func templateFor(m *installed) (string, []string) {
	if m.Template != "" {
		return m.Template, nil
	}
	switch {
	case strings.HasPrefix(m.Arch, "qwen") || m.Family == "deepseek-r1":
		return "{{- if .System }}<|im_start|>system\n{{ .System }}<|im_end|>\n{{ end }}{{- range .Messages }}<|im_start|>{{ .Role }}\n{{ .Content }}<|im_end|>\n{{ end }}<|im_start|>assistant\n",
			[]string{"<|im_start|>", "<|im_end|>"}
	case strings.HasPrefix(m.Arch, "llama") || m.Arch == "mllama":
		return "<|start_header_id|>system<|end_header_id|>\n\n{{ .System }}<|eot_id|>{{- range .Messages }}<|start_header_id|>{{ .Role }}<|end_header_id|>\n\n{{ .Content }}<|eot_id|>{{ end }}<|start_header_id|>assistant<|end_header_id|>\n\n",
			[]string{"<|start_header_id|>", "<|end_header_id|>", "<|eot_id|>"}
	case strings.HasPrefix(m.Arch, "gemma"):
		return "{{- range .Messages }}<start_of_turn>{{ if eq .Role \"user\" }}user{{ else }}model{{ end }}\n{{ .Content }}<end_of_turn>\n{{ end }}<start_of_turn>model\n",
			[]string{"<end_of_turn>"}
	case m.Has("embedding"):
		return "{{ .Prompt }}", nil
	}
	return "{{ if .System }}{{ .System }}\n\n{{ end }}{{ .Prompt }}", nil
}

func licenseFor(m Model) string {
	switch {
	case strings.HasPrefix(m.Family, "llama"):
		return "LLAMA COMMUNITY LICENSE AGREEMENT"
	case strings.HasPrefix(m.Family, "gemma") || m.Family == "embeddinggemma":
		return "Gemma Terms of Use"
	case m.Family == "":
		return ""
	}
	return "Apache License\nVersion 2.0, January 2004\nhttp://www.apache.org/licenses/"
}

type layer struct {
	digest    string
	size      int64
	mediaType string
}

func layersFor(m Model) []layer {
	weights := m.Size - 13000
	ls := []layer{{sha256hex("weights", m.Digest), weights, "model"}}
	if m.Has("vision") {
		proj := m.Size / 9
		ls[0].size -= proj
		ls = append(ls, layer{sha256hex("projector", m.Digest), proj, "projector"})
	}
	ls = append(ls,
		layer{sha256hex("template", m.Arch), 1400, "template"},
		layer{sha256hex("license", m.Family), 11300, "license"},
		layer{sha256hex("params", m.Arch), 120, "params"},
	)
	return ls
}

type ndjson struct {
	w       http.ResponseWriter
	stream  bool
	started bool
}

func (n *ndjson) send(v any) {
	if !n.stream {
		return
	}
	if !n.started {
		n.w.Header().Set("Content-Type", "application/x-ndjson")
		n.w.WriteHeader(200)
		n.started = true
	}
	b, _ := json.Marshal(v)
	n.w.Write(append(b, '\n'))
	if f, ok := n.w.(http.Flusher); ok {
		f.Flush()
	}
}

// fail ends a progress stream: an error line when streaming (Ollama has already sent 200), else
// a 500 with the error.
func (n *ndjson) fail(msg string) {
	if n.stream {
		n.send(map[string]any{"error": msg})
		return
	}
	writeError(n.w, 500, msg)
}

func (n *ndjson) done(v any) {
	if n.stream {
		n.send(v)
		return
	}
	writeJSON(n.w, 200, v)
}

func streamFlag(p *bool) bool { return p == nil || *p }

func (s *Server) handlePull(w http.ResponseWriter, r *http.Request) {
	var body struct {
		Model    string `json:"model"`
		Name     string `json:"name"`
		Insecure bool   `json:"insecure"`
		Stream   *bool  `json:"stream"`
	}
	if err := decode(r, &body); err != nil {
		writeError(w, 400, err.Error())
		return
	}
	name := Normalize(body.Model)
	if name == "" {
		name = Normalize(body.Name)
	}
	noteModel(r, name)
	if name == "" {
		writeError(w, 400, "model is required")
		return
	}
	out := &ndjson{w: w, stream: streamFlag(body.Stream)}
	ctx := r.Context()
	out.send(map[string]any{"status": "pulling manifest"})
	if !s.sleep(ctx, 400*time.Millisecond) {
		return
	}
	s.mu.Lock()
	missing := slices.Contains(s.faults.Missing, name)
	pullErr := s.faults.Models[name].PullError
	_, have := s.models[name]
	s.mu.Unlock()
	if missing {
		out.fail("pull model manifest: file does not exist")
		return
	}
	if pullErr != "" {
		out.fail(pullErr)
		return
	}
	m := Describe(name)
	for _, l := range layersFor(m) {
		status := "pulling " + l.digest[:12]
		steps := int64(1)
		if l.size > 50e6 && !have {
			steps = 20
		}
		for i := int64(0); i <= steps; i++ {
			done := l.size * i / steps
			if i == 0 && steps == 1 {
				continue
			}
			out.send(map[string]any{"status": status, "digest": "sha256:" + l.digest, "total": l.size, "completed": done})
			if i < steps && !have && !s.sleep(ctx, time.Duration(float64(l.size)/float64(steps)/s.opts.PullSpeed*float64(time.Second))) {
				return
			}
		}
	}
	for _, st := range []string{"verifying sha256 digest", "writing manifest"} {
		out.send(map[string]any{"status": st})
		if !s.sleep(ctx, 150*time.Millisecond) {
			return
		}
	}
	s.mu.Lock()
	s.models[name] = &installed{Model: m, Modified: s.stamp()}
	s.mu.Unlock()
	out.done(map[string]any{"status": "success"})
}

func (s *Server) handlePush(w http.ResponseWriter, r *http.Request) {
	var body struct {
		Model    string `json:"model"`
		Name     string `json:"name"`
		Insecure bool   `json:"insecure"`
		Stream   *bool  `json:"stream"`
	}
	if err := decode(r, &body); err != nil {
		writeError(w, 400, err.Error())
		return
	}
	name := body.Model
	if name == "" {
		name = body.Name
	}
	noteModel(r, name)
	m, err := s.lookup(name)
	if err != nil {
		writeError(w, 404, fmt.Sprintf("model %q not found", name))
		return
	}
	out := &ndjson{w: w, stream: streamFlag(body.Stream)}
	out.send(map[string]any{"status": "retrieving manifest"})
	if !strings.Contains(m.Name, "/") {
		out.fail("you are not authorized to push to this namespace, create the model under a namespace you own")
		return
	}
	for _, l := range layersFor(m.Model) {
		out.send(map[string]any{"status": "pushing " + l.digest[:12], "digest": "sha256:" + l.digest, "total": l.size, "completed": l.size})
		if !s.sleep(r.Context(), time.Duration(float64(l.size)/s.opts.PullSpeed*float64(time.Second))) {
			return
		}
	}
	out.send(map[string]any{"status": "pushing manifest"})
	out.done(map[string]any{"status": "success"})
}

func (s *Server) handleCreate(w http.ResponseWriter, r *http.Request) {
	var body struct {
		Model      string            `json:"model"`
		Name       string            `json:"name"`
		From       string            `json:"from"`
		Files      map[string]string `json:"files"`
		Template   string            `json:"template"`
		System     string            `json:"system"`
		Parameters map[string]any    `json:"parameters"`
		Quantize   string            `json:"quantize"`
		Stream     *bool             `json:"stream"`
	}
	if err := decode(r, &body); err != nil {
		writeError(w, 400, err.Error())
		return
	}
	name := Normalize(body.Model)
	if name == "" {
		name = Normalize(body.Name)
	}
	noteModel(r, name)
	if name == "" {
		writeError(w, 400, "model is required")
		return
	}
	var base Model
	parent := ""
	switch {
	case body.From != "":
		from, err := s.lookup(body.From)
		if err != nil {
			writeError(w, 404, fmt.Sprintf("model %q not found", body.From))
			return
		}
		base, parent = from.Model, from.Name
	case len(body.Files) > 0:
		base = Describe(name)
	default:
		writeError(w, 400, "neither 'from' or 'files' was specified")
		return
	}
	out := &ndjson{w: w, stream: streamFlag(body.Stream)}
	for _, l := range layersFor(base) {
		out.send(map[string]any{"status": "using existing layer sha256:" + l.digest})
	}
	m := base
	m.Name = name
	if body.Quantize != "" {
		q := strings.ToUpper(body.Quantize)
		out.send(map[string]any{"status": fmt.Sprintf("quantizing %s model to %s", base.Quant, q)})
		if !s.sleep(r.Context(), time.Duration(base.Params*float64(time.Second))) {
			return
		}
		m.Size = int64(float64(base.Size) * bytesPerParam(q) / bytesPerParam(base.Quant))
		m.Quant = q
	}
	for _, part := range []string{body.Template, body.System, fmt.Sprint(body.Parameters)} {
		if part != "" && part != "map[]" {
			out.send(map[string]any{"status": "creating new layer sha256:" + sha256hex("layer", part)})
		}
	}
	m.Digest = sha256hex("ollama-mock", "create", name, base.Digest, body.Template, body.System, fmt.Sprint(body.Parameters), m.Quant)
	out.send(map[string]any{"status": "writing manifest"})
	s.mu.Lock()
	s.models[name] = &installed{Model: m, Modified: s.stamp(), System: body.System, Template: body.Template, Parameters: body.Parameters, Parent: parent}
	s.mu.Unlock()
	out.done(map[string]any{"status": "success"})
}

func (s *Server) handleCopy(w http.ResponseWriter, r *http.Request) {
	var body struct {
		Source      string `json:"source"`
		Destination string `json:"destination"`
	}
	if err := decode(r, &body); err != nil {
		writeError(w, 400, err.Error())
		return
	}
	noteModel(r, body.Source)
	src, err := s.lookup(body.Source)
	if err != nil {
		writeError(w, 404, fmt.Sprintf("model %q not found", body.Source))
		return
	}
	dst := Normalize(body.Destination)
	if dst == "" {
		writeError(w, 400, "destination is required")
		return
	}
	c := *src
	c.Name, c.Modified = dst, s.stamp()
	s.mu.Lock()
	s.models[dst] = &c
	s.mu.Unlock()
	w.WriteHeader(200)
}

func (s *Server) handleDelete(w http.ResponseWriter, r *http.Request) {
	var body struct {
		Model string `json:"model"`
		Name  string `json:"name"`
	}
	if err := decode(r, &body); err != nil {
		writeError(w, 400, err.Error())
		return
	}
	name := Normalize(body.Model)
	if name == "" {
		name = Normalize(body.Name)
	}
	noteModel(r, name)
	if f := s.modelFaults(name); f.DeleteError != "" {
		writeError(w, 500, f.DeleteError)
		return
	}
	s.mu.Lock()
	_, ok := s.models[name]
	delete(s.models, name)
	delete(s.loaded, name)
	s.mu.Unlock()
	if !ok {
		writeError(w, 404, fmt.Sprintf("model '%s' not found", body.Model+body.Name))
		return
	}
	w.WriteHeader(200)
}

func (s *Server) handleBlobHead(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	ok := s.blobs[r.PathValue("digest")]
	s.mu.Unlock()
	if !ok {
		w.WriteHeader(404)
		return
	}
	w.WriteHeader(200)
}

func (s *Server) handleBlobPost(w http.ResponseWriter, r *http.Request) {
	d := r.PathValue("digest")
	if !strings.HasPrefix(d, "sha256:") && !strings.HasPrefix(d, "sha256-") {
		writeError(w, 400, "invalid digest format")
		return
	}
	s.mu.Lock()
	s.blobs[d] = true
	s.mu.Unlock()
	w.WriteHeader(201)
}
